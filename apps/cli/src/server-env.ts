// The server's .env for docker/compose.yml: parsing, merging without losing comments or keys,
// and generating its secrets. Pure (no I/O), so `mybase server` can be tested without Docker.

/** The secrets compose.yml needs, and how each is generated. Never regenerated once set. */
export const SECRET_KEYS = {
  POSTGRES_PASSWORD: { bytes: 24, encoding: "hex" },
  GARAGE_RPC_SECRET: { bytes: 32, encoding: "hex" },
  GARAGE_ADMIN_TOKEN: { bytes: 32, encoding: "hex" },
  VALKEY_PASSWORD: { bytes: 32, encoding: "hex" },
  SEARXNG_SECRET: { bytes: 32, encoding: "hex" },
  MYBASE_SECRETS_KEY: { bytes: 32, encoding: "base64" },
} as const;

export type SecretKey = keyof typeof SECRET_KEYS;

/** Sections of a fresh .env, in order. Keys not listed go under "Other". */
const SECTIONS: { title: string; keys: string[] }[] = [
  {
    title: "Secrets (generated by `mybase server setup`). Changing one breaks the data it protects.\n# Back up MYBASE_SECRETS_KEY somewhere other than this machine: without it, stored secrets are lost.",
    keys: Object.keys(SECRET_KEYS),
  },
  {
    title: "Access: where apps and the dashboard reach this machine",
    keys: ["MYBASE_PORT", "MYBASE_PUBLIC_HOST", "MYBASE_PUBLIC_URL", "MYBASE_S3_PUBLIC_URL", "MYBASE_TRUST_PROXY", "POSTGRES_PORT", "GARAGE_S3_PORT", "VALKEY_PORT", "POSTGRES_BIND", "GARAGE_S3_BIND", "VALKEY_BIND"],
  },
  { title: "Cloudflare Tunnel (public HTTPS without opening router ports)", keys: ["COMPOSE_PROFILES", "CLOUDFLARE_TUNNEL_TOKEN"] },
  { title: "Startup: `no` keeps mybase from starting again after a reboot or crash", keys: ["MYBASE_RESTART"] },
  { title: "Tuning", keys: ["CACHE_MAXMEMORY", "GARAGE_CAPACITY", "MYBASE_MAX_UPLOAD", "LOG_LEVEL"] },
];

const LINE = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$/;

function unquote(raw: string): string {
  const value = raw.trim();
  const quote = value[0];
  if ((quote === '"' || quote === "'") && value.endsWith(quote) && value.length >= 2) return value.slice(1, -1);
  // Unquoted: a ` #` starts a comment.
  return value.replace(/\s+#.*$/, "");
}

/** Single quotes when needed: Compose leaves single-quoted values alone (no `$` interpolation). */
function quote(value: string): string {
  return /^[A-Za-z0-9_./:+=@,-]*$/.test(value) ? value : `'${value.replaceAll("'", "")}'`;
}

export function parseEnv(text: string): Record<string, string> {
  const values: Record<string, string> = {};
  for (const line of text.split(/\r?\n/)) {
    const match = LINE.exec(line);
    if (match) values[match[1]!] = unquote(match[2]!);
  }
  return values;
}

/** A fresh .env, grouped into commented sections. */
export function renderEnv(values: Record<string, string>): string {
  const blocks: string[] = [];
  const listed = new Set(SECTIONS.flatMap((s) => s.keys));
  const sections = [...SECTIONS, { title: "Other", keys: Object.keys(values).filter((k) => !listed.has(k)) }];
  for (const { title, keys } of sections) {
    const lines = keys.filter((k) => values[k] !== undefined).map((k) => `${k}=${quote(values[k]!)}`);
    if (lines.length) blocks.push(`# ${title}\n${lines.join("\n")}`);
  }
  return `# mybase server settings, read by compose.yml. Change with \`mybase server setup\` or by hand,\n# then run \`docker compose up -d\`.\n\n${blocks.join("\n\n")}\n`;
}

/**
 * Applies `updates` to an existing .env: changed keys are replaced in place, `null` removes a key,
 * new keys are appended. Comments, order, and keys we don't know stay as they are.
 */
export function mergeEnv(text: string, updates: Record<string, string | null>): string {
  const pending = new Map(Object.entries(updates));
  const lines: string[] = [];
  for (const line of text.replace(/\n+$/, "").split(/\r?\n/)) {
    const key = LINE.exec(line)?.[1];
    if (!key || !pending.has(key)) {
      lines.push(line);
      continue;
    }
    const value = pending.get(key);
    pending.delete(key);
    if (value !== null && value !== undefined) lines.push(`${key}=${quote(value)}`);
  }
  const added = [...pending].filter((entry): entry is [string, string] => entry[1] !== null);
  if (added.length) lines.push("", "# Added by `mybase server setup`", ...added.map(([k, v]) => `${k}=${quote(v)}`));
  return `${lines.join("\n")}\n`;
}

/** Random values for the secrets `existing` doesn't have yet. */
export function generateSecrets(existing: Record<string, string> = {}): Partial<Record<SecretKey, string>> {
  const out: Partial<Record<SecretKey, string>> = {};
  for (const [key, { bytes, encoding }] of Object.entries(SECRET_KEYS) as [SecretKey, (typeof SECRET_KEYS)[SecretKey]][]) {
    if (existing[key]) continue;
    out[key] = Buffer.from(crypto.getRandomValues(new Uint8Array(bytes))).toString(encoding);
  }
  return out;
}

export const isSecretKey = (key: string) => key in SECRET_KEYS || key === "CLOUDFLARE_TUNNEL_TOKEN";

/** `a1b2…f9e0` for showing a secret without revealing it. */
export function maskSecret(value: string): string {
  return value.length <= 8 ? "••••" : `${value.slice(0, 4)}…${value.slice(-4)}`;
}

/** The tunnel ID inside a Cloudflare tunnel token (base64 JSON `{ a, t, s }`), or null if it isn't one. */
export function tunnelIdFromToken(token: string): string | null {
  try {
    const parsed = JSON.parse(Buffer.from(token.trim(), "base64").toString("utf8")) as { a?: unknown; t?: unknown; s?: unknown };
    return typeof parsed.t === "string" && typeof parsed.a === "string" && typeof parsed.s === "string" ? parsed.t : null;
  } catch {
    return null;
  }
}

/** The .env keys for a tunnel serving `mybase.<domain>`-style hostnames. */
export function tunnelEnv(token: string, apiHost: string, s3Host: string): Record<string, string> {
  return {
    COMPOSE_PROFILES: "tunnel",
    CLOUDFLARE_TUNNEL_TOKEN: token,
    MYBASE_PUBLIC_URL: `https://${apiHost}`,
    MYBASE_S3_PUBLIC_URL: `https://${s3Host}`,
    MYBASE_TRUST_PROXY: "cloudflare",
  };
}

/** `2.29.1` ≥ `2.23.1`? (Docker Compose versions, with or without a leading `v`.) */
export function versionAtLeast(version: string, min: string): boolean {
  const parts = (v: string) => v.replace(/^v/, "").split(/[.-]/).slice(0, 3).map((n) => Number.parseInt(n, 10) || 0);
  const a = parts(version);
  const b = parts(min);
  for (let i = 0; i < 3; i++) if ((a[i] ?? 0) !== (b[i] ?? 0)) return (a[i] ?? 0) > (b[i] ?? 0);
  return true;
}
