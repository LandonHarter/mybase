// Writes docs/cli.md from the CLI's own usage strings, so the reference can't drift.
//   bun scripts/gen-cli-docs.ts          write it
//   bun scripts/gen-cli-docs.ts --check  exit 1 if it's out of date (bun test runs this)
import { resolve } from "node:path";

import { homedir } from "node:os";
import { configPath } from "../apps/cli/src/config";
import { GLOBAL_FLAGS, USAGE } from "../apps/cli/src/index";

const TITLES: Record<string, string> = {
  auth: "Sign in",
  server: "Server (install + run)",
  token: "API keys",
  project: "Projects",
  context: "Project context",
  docs: "Docs",
  mcp: "MCP setup",
  agent: "Agent setup",
  cron: "Cron",
  analytics: "Analytics",
  cache: "Cache",
  ratelimit: "Rate limits",
  queue: "Queues",
};

// Usage text mentions this machine's config path: write the default one instead.
const dedent = (text: string) =>
  text
    .replace(/^  /gm, "")
    .replaceAll(configPath, "~/.config/mybase/config.json")
    .replaceAll(configPath.replace(homedir(), "~"), "~/.config/mybase/config.json");

const page = `---
title: CLI reference
summary: Every mybase CLI command and flag, generated from the CLI itself. Global flags --json and --yes, exit codes.
section: Reference
order: 20
---

# CLI reference

<!-- Generated by scripts/gen-cli-docs.ts from the CLI's usage text. Don't edit by hand. -->

Install: see [Quickstart](quickstart.md). Every command talks to the server in \`MYBASE_API_URL\` (or the one saved by \`mybase login\`).

## Global flags

\`\`\`
${dedent(GLOBAL_FLAGS)}
\`\`\`

${Object.entries(USAGE)
  .map(([key, usage]) => `## ${TITLES[key] ?? key}\n\n\`\`\`\n${dedent(usage)}\n\`\`\``)
  .join("\n\n")}

## Agent notes

- Add \`--json\` whenever you parse output; read errors from stderr as JSON.
- \`mybase help <command>\` prints one command's usage.
`;

const path = resolve(import.meta.dir, "../docs/cli.md");
if (process.argv.includes("--check")) {
  const current = await Bun.file(path).text().catch(() => "");
  if (current !== page) {
    console.error("docs/cli.md is out of date: run bun scripts/gen-cli-docs.ts");
    process.exit(1);
  }
} else {
  await Bun.write(path, page);
  console.log(`wrote ${path}`);
}
