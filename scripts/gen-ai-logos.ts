#!/usr/bin/env bun
// Regenerates apps/dashboard/src/pages/ai/logos.ts: provider and model-maker logos for the AI
// gateway pages, from models.dev (MIT). Bundled because the dashboard works offline and its CSP
// only allows images from itself. The SVGs are monochrome (currentColor), so they follow the theme.
// Run when a provider is added to ai-providers.ts or a new maker shows up in the catalog.
import { join } from "node:path";
import { AI_PROVIDERS } from "../apps/api/src/ai-providers";

// Makers of models sold through gateways (vercel/<maker>/…, openrouter/<maker>/…), by models.dev logo id.
const MAKERS = ["alibaba", "meta", "zai", "nvidia", "moonshotai", "minimax", "xiaomi"];

const ids = [...new Set([...Object.values(AI_PROVIDERS).flatMap((p) => (p.pricesId ? [p.pricesId] : [])), ...MAKERS])].sort();

async function get(id: string): Promise<string> {
  const res = await fetch(`https://models.dev/logos/${id}.svg`, { signal: AbortSignal.timeout(20_000) });
  if (!res.ok) throw new Error(`models.dev answered ${res.status} for ${id}`);
  return (await res.text()).trim();
}

// models.dev answers unknown ids with a generic logo; skip those.
const fallback = await get("mybase-no-such-provider");
const logos: Record<string, string> = {};
for (const id of ids) {
  const svg = await get(id);
  if (svg === fallback) {
    console.log(`skip ${id}: no logo`);
    continue;
  }
  // Inlined with dangerouslySetInnerHTML: refuse anything that isn't plain shapes.
  if (!/^<svg[\s>]/.test(svg) || /<(script|style|foreignObject|image|a|use)\b|\bhref\b|\son\w+\s*=|url\(/i.test(svg)) throw new Error(`${id}: unexpected SVG content`);
  logos[id] = svg
    .replace(/<\?xml[^>]*>/, "")
    .replace(/<svg([^>]*?)\s(width|height)="[^"]*"/g, "<svg$1")
    .replace(/<svg([^>]*?)\s(width|height)="[^"]*"/g, "<svg$1")
    .replace(/\s*\n\s*/g, " ");
}

const out = join(import.meta.dir, "../apps/dashboard/src/pages/ai/logos.ts");
await Bun.write(
  out,
  `// Generated by scripts/gen-ai-logos.ts from models.dev (MIT). Don't edit by hand.\n// models.dev logo id → SVG markup (currentColor).\nexport const LOGOS: Record<string, string> = ${JSON.stringify(logos, null, 2)};\n`,
);
console.log(`wrote ${out}: ${Object.keys(logos).length} logos`);
